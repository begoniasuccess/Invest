BEGIN;

CREATE TABLE IF NOT EXISTS ml_model (
    model_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    model_key text NOT NULL UNIQUE,
    model_name text NOT NULL,
    description text,
    target_market text NOT NULL,
    target_name text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ml_model_version (
    model_version_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    model_id uuid NOT NULL REFERENCES ml_model(model_id) ON DELETE CASCADE,
    version_no integer NOT NULL CHECK (version_no > 0),
    algorithm text NOT NULL,
    source_relation text NOT NULL,
    entity_filter jsonb NOT NULL DEFAULT '{}'::jsonb,
    feature_columns jsonb NOT NULL,
    target_config jsonb NOT NULL,
    model_params jsonb NOT NULL DEFAULT '{}'::jsonb,
    training_config jsonb NOT NULL DEFAULT '{}'::jsonb,
    config_snapshot jsonb NOT NULL,
    config_hash text NOT NULL,
    code_version text,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('draft', 'active', 'retired', 'failed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (model_id, version_no),
    UNIQUE (model_id, config_hash)
);

CREATE TABLE IF NOT EXISTS ml_prediction_run (
    run_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    model_version_id uuid NOT NULL
        REFERENCES ml_model_version(model_version_id) ON DELETE CASCADE,
    run_type text NOT NULL CHECK (run_type IN ('single', 'backtest', 'live')),
    requested_start_date date NOT NULL,
    requested_end_date date NOT NULL,
    train_start_date date,
    train_end_date date,
    row_count integer,
    random_seed integer,
    runtime_params jsonb NOT NULL DEFAULT '{}'::jsonb,
    metrics jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'completed', 'partial', 'failed')),
    error_message text,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz
);

CREATE TABLE IF NOT EXISTS ml_prediction (
    prediction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id uuid NOT NULL REFERENCES ml_prediction_run(run_id) ON DELETE CASCADE,
    model_version_id uuid NOT NULL
        REFERENCES ml_model_version(model_version_id) ON DELETE CASCADE,
    target_date date NOT NULL,
    feature_date date NOT NULL,
    trained_through_date date NOT NULL,
    predicted_class smallint NOT NULL CHECK (predicted_class IN (-1, 0, 1)),
    predicted_label text NOT NULL,
    probability_down double precision,
    probability_flat double precision,
    probability_up double precision,
    confidence double precision CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1),
    feature_values jsonb NOT NULL,
    actual_class smallint CHECK (actual_class IS NULL OR actual_class IN (-1, 0, 1)),
    actual_label text,
    actual_return_pct double precision,
    is_correct boolean GENERATED ALWAYS AS (
        CASE WHEN actual_class IS NULL THEN NULL ELSE predicted_class = actual_class END
    ) STORED,
    predicted_at timestamptz NOT NULL DEFAULT now(),
    actual_updated_at timestamptz,
    UNIQUE (run_id, target_date)
);

CREATE INDEX IF NOT EXISTS ix_ml_prediction_version_date
    ON ml_prediction(model_version_id, target_date);
CREATE INDEX IF NOT EXISTS ix_ml_prediction_unrealized
    ON ml_prediction(target_date) WHERE actual_class IS NULL;
CREATE INDEX IF NOT EXISTS ix_ml_prediction_run_version
    ON ml_prediction_run(model_version_id, started_at DESC);

CREATE OR REPLACE VIEW v_ml_model_performance AS
WITH latest_prediction AS (
    SELECT DISTINCT ON (model_version_id, target_date) *
    FROM ml_prediction
    ORDER BY model_version_id, target_date, predicted_at DESC, prediction_id DESC
)
SELECT
    m.model_key,
    m.model_name,
    v.version_no,
    v.algorithm,
    count(p.prediction_id) AS prediction_count,
    count(p.actual_class) AS realized_count,
    count(*) FILTER (WHERE p.is_correct) AS correct_count,
    round(
        100.0 * count(*) FILTER (WHERE p.is_correct)
        / NULLIF(count(p.actual_class), 0), 2
    ) AS accuracy_pct,
    min(p.target_date) AS first_prediction_date,
    max(p.target_date) AS last_prediction_date
FROM ml_model m
JOIN ml_model_version v ON v.model_id = m.model_id
LEFT JOIN latest_prediction p ON p.model_version_id = v.model_version_id
GROUP BY m.model_key, m.model_name, v.version_no, v.algorithm;

-- p_confirm=false 只預覽筆數；true 才刪除。最上層刪除後由 FK 連動清除。
CREATE OR REPLACE FUNCTION ml_delete_model(
    p_model_key text,
    p_confirm boolean DEFAULT false
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_model_id uuid;
    v_result jsonb;
BEGIN
    SELECT model_id INTO v_model_id FROM ml_model WHERE model_key = p_model_key;
    IF v_model_id IS NULL THEN
        RAISE EXCEPTION 'model_key % does not exist', p_model_key;
    END IF;

    SELECT jsonb_build_object(
        'model_key', p_model_key,
        'versions', (SELECT count(*) FROM ml_model_version WHERE model_id = v_model_id),
        'runs', (SELECT count(*) FROM ml_prediction_run r JOIN ml_model_version v USING (model_version_id) WHERE v.model_id = v_model_id),
        'predictions', (SELECT count(*) FROM ml_prediction p JOIN ml_model_version v USING (model_version_id) WHERE v.model_id = v_model_id),
        'deleted', p_confirm
    ) INTO v_result;

    IF p_confirm THEN
        DELETE FROM ml_model WHERE model_id = v_model_id;
    END IF;
    RETURN v_result;
END;
$$;

COMMIT;
