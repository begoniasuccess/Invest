CREATE INDEX IF NOT EXISTS idx_fm_futures_kbar_1m_period_query
    ON public.fm_taiwan_futures_kbar_1m (futures_id, trading_session, bar_datetime, contract_date)
    INCLUDE (open, high, low, close, volume, trading_date);

COMMIT;
