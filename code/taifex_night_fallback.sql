BEGIN;

CREATE TABLE IF NOT EXISTS public.taifex_futures_daily (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date date NOT NULL,
    futures_id text NOT NULL,
    contract_month text NOT NULL,
    trading_session text NOT NULL,
    open double precision,
    high double precision,
    low double precision,
    close double precision,
    volume bigint,
    settlement_price double precision,
    open_interest bigint,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_taifex_futures_daily UNIQUE (trade_date, futures_id, contract_month, trading_session),
    CONSTRAINT ck_taifex_futures_daily_session CHECK (trading_session IN ('position', 'after_market')),
    CONSTRAINT ck_taifex_futures_daily_ohlc CHECK (
        high IS NULL OR low IS NULL OR open IS NULL OR close IS NULL OR
        (high >= GREATEST(open, close, low) AND low <= LEAST(open, close, high))
    ),
    CONSTRAINT ck_taifex_futures_daily_volume CHECK (volume IS NULL OR volume >= 0)
);

CREATE INDEX IF NOT EXISTS idx_taifex_futures_daily_lookup
    ON public.taifex_futures_daily (futures_id, trade_date DESC, trading_session, contract_month);
CREATE INDEX IF NOT EXISTS idx_taifex_futures_daily_night
    ON public.taifex_futures_daily (futures_id, trade_date DESC, contract_month)
    WHERE trading_session = 'after_market';

COMMENT ON TABLE public.taifex_futures_daily IS
    '臺灣期貨交易所官方期貨每日交易行情；與 FinMind 分開保存，供缺檔備援與來源稽核。';

CREATE OR REPLACE VIEW public.v_taifex_tx_night_fallback AS
WITH official_front AS (
    SELECT d.*,
        row_number() OVER (
            PARTITION BY d.trade_date, d.futures_id
            ORDER BY d.volume DESC NULLS LAST, d.contract_month ASC
        ) AS contract_rank
    FROM public.taifex_futures_daily d
    WHERE d.trading_session = 'after_market'
      AND d.contract_month ~ '^[0-9]{6}$'
), mapped AS (
    SELECT previous_day.report_date, o.trade_date AS official_trade_date,
        o.futures_id, o.contract_month, o.open, o.close, o.high, o.low, o.volume
    FROM official_front o
    JOIN LATERAL (
        SELECT max(f.date) AS report_date
        FROM public.fm_taiwan_futures_daily f
        WHERE f.futures_id = o.futures_id
          AND f.trading_session = 'position'
          AND f.date < o.trade_date
    ) previous_day ON previous_day.report_date IS NOT NULL
    WHERE o.contract_rank = 1
)
SELECT r.futures_id, r."日期" AS report_date, m.official_trade_date, m.contract_month,
    COALESCE(r."夜盤開", m.open) AS open,
    COALESCE(r."夜盤收", m.close) AS close,
    COALESCE(r."夜盤高", m.high) AS high,
    COALESCE(r."夜盤低", m.low) AS low,
    COALESCE(r."夜成交量", m.volume) AS volume,
    CASE
        WHEN EXISTS (
            SELECT 1 FROM public.fm_taiwan_futures_daily fm
            WHERE fm.futures_id = r.futures_id
              AND fm.date = m.official_trade_date
              AND fm.trading_session = 'after_market'
              AND fm.open IS NOT NULL AND fm.close IS NOT NULL
              AND fm.max IS NOT NULL AND fm.min IS NOT NULL
        ) THEN 'FinMind'
        WHEN m.open IS NOT NULL AND m.close IS NOT NULL
         AND m.high IS NOT NULL AND m.low IS NOT NULL THEN 'TAIFEX'
        WHEN r."夜盤開" IS NOT NULL AND r."夜盤收" IS NOT NULL
         AND r."夜盤高" IS NOT NULL AND r."夜盤低" IS NOT NULL THEN '既有資料'
        ELSE NULL
    END AS data_source
FROM public.futures_report_daily_raw r
LEFT JOIN mapped m ON m.futures_id = r.futures_id AND m.report_date = r."日期";

COMMENT ON VIEW public.v_taifex_tx_night_fallback IS
    '期貨夜盤行情優先採 FinMind，缺少開收高低時改採期交所官方資料。';

DO $migration$
BEGIN
    IF to_regclass('public.v_futures_report_daily_base') IS NULL
       AND to_regclass('public.v_futures_report_daily') IS NOT NULL THEN
        ALTER VIEW public.v_futures_report_daily RENAME TO v_futures_report_daily_base;
    END IF;
END
$migration$;

DO $view_builder$
DECLARE
    column_list text;
BEGIN
    SELECT string_agg(
        CASE attribute.attname
            WHEN '夜盤開' THEN 'COALESCE(base."夜盤開", fallback.open) AS "夜盤開"'
            WHEN '夜盤收' THEN 'COALESCE(base."夜盤收", fallback.close) AS "夜盤收"'
            WHEN '夜盤高' THEN 'COALESCE(base."夜盤高", fallback.high) AS "夜盤高"'
            WHEN '夜盤低' THEN 'COALESCE(base."夜盤低", fallback.low) AS "夜盤低"'
            WHEN '夜成交量' THEN 'COALESCE(base."夜成交量", fallback.volume) AS "夜成交量"'
            ELSE format('base.%I', attribute.attname)
        END,
        ', ' ORDER BY attribute.attnum
    ) INTO column_list
    FROM pg_attribute attribute
    WHERE attribute.attrelid = 'public.v_futures_report_daily_base'::regclass
      AND attribute.attnum > 0
      AND NOT attribute.attisdropped;

    EXECUTE 'CREATE OR REPLACE VIEW public.v_futures_report_daily AS SELECT '
        || column_list
        || ', fallback.data_source AS "夜盤資料來源" '
        || 'FROM public.v_futures_report_daily_base base '
        || 'LEFT JOIN public.v_taifex_tx_night_fallback fallback '
        || 'ON fallback.futures_id = base.futures_id AND fallback.report_date = base."日期"';
END
$view_builder$;

COMMENT ON VIEW public.v_futures_report_daily IS
    '期貨指數完整報表；夜盤優先採 FinMind，缺檔時由期交所官方行情補足，夜盤資料來源欄可供稽核。';

CREATE INDEX IF NOT EXISTS idx_fm_stock_kbar_1m_period_query
