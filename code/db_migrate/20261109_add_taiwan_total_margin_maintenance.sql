BEGIN;

CREATE TABLE IF NOT EXISTS raw_finmind.fm_taiwan_total_exchange_margin_maintenance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    total_exchange_margin_maintenance double precision NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fm_tw_total_margin_maintenance_date UNIQUE (date),
    CONSTRAINT ck_fm_tw_total_margin_maintenance_positive
        CHECK (total_exchange_margin_maintenance > 0)
);

COMMENT ON TABLE raw_finmind.fm_taiwan_total_exchange_margin_maintenance IS
    'FinMind TaiwanTotalExchangeMarginMaintenance 台灣大盤融資維持率原始資料；暫不併入期貨報表 view。';

COMMENT ON COLUMN raw_finmind.fm_taiwan_total_exchange_margin_maintenance.date IS
    'FinMind 資料日期（台灣市場交易日）。';

COMMENT ON COLUMN raw_finmind.fm_taiwan_total_exchange_margin_maintenance.total_exchange_margin_maintenance IS
    'FinMind 大盤融資維持率，單位為百分比，例如 166.007 代表 166.007%。';

CREATE INDEX IF NOT EXISTS idx_fm_tw_total_margin_maintenance_date_desc
    ON raw_finmind.fm_taiwan_total_exchange_margin_maintenance (date DESC);

COMMIT;
